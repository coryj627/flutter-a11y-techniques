#!/usr/bin/env python3
"""L4 for C01 Button on iOS: capture and check what VoiceOver speaks.

Runs C01ButtonUITests/testVoiceOverSpeech on an iOS 27 simulator. The test
drives VoiceOver through XCUIVoiceOverService and asserts the phrases; this
script writes the transcript to docs/evidence/C01/voiceover-ios.md.

Usage: python3 tool/voiceover_ios_c01.py ["iPhone 17"]
"""
import datetime
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEVICE = sys.argv[1] if len(sys.argv) > 1 else "iPhone 17"


def main():
    run = subprocess.run(
        ["xcodebuild", "test", "-workspace", "Runner.xcworkspace", "-scheme", "Runner",
         "-configuration", "Debug", "-destination", f"platform=iOS Simulator,name={DEVICE}",
         "-only-testing:RunnerUITests/C01ButtonUITests/testVoiceOverSpeech",
         "-derivedDataPath", os.path.join(ROOT, "build", "ios_uitest")],
        cwd=os.path.join(ROOT, "ios"), capture_output=True, text=True)
    log = run.stdout + run.stderr
    rows = re.findall(r"^C01VO (\S+) \| (.*)$", log, re.M)
    failures = re.findall(r"error: .*? : (.*)$", log, re.M)
    if not rows:
        print(log[-3000:])
        sys.exit("No VoiceOver transcript captured.")
    os_version = re.search(r"OS:(\d+(?:\.\d+)*)", log) or re.search(r"iOS (\d+(?:\.\d+)*)", log)
    xcode = subprocess.run(["xcodebuild", "-version"], capture_output=True, text=True).stdout.split("\n")[0]
    passed = run.returncode == 0
    out = ["# C01 Button: VoiceOver transcript (iOS)", "",
           "Generated by `tool/voiceover_ios_c01.py`. Do not edit by hand.", "",
           f"- Date: {datetime.date.today().isoformat()}",
           f"- Device: {DEVICE} (simulator)",
           f"- iOS: {os_version.group(1) if os_version else 'unknown'}",
           f"- {xcode}",
           f"- Flutter: {open(os.path.join(ROOT, '.fvmrc')).read().split(chr(34))[3]}",
           "- Method: `XCUIVoiceOverService.moveForward()` from the top of each example "
           "screen to the activation count; utterances are cut at 64 characters by the API",
           "", f"Result: {'PASS' if passed else 'FAIL'}", "",
           "| Example | Spoken, in swipe order |", "| --- | --- |"]
    out += [f"| `{slug}` | {spoken} |" for slug, spoken in rows]
    if failures:
        out += ["", "## Failures", ""] + [f"- {f}" for f in failures]
    with open(os.path.join(ROOT, "docs", "evidence", "C01", "voiceover-ios.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
