/// Writes the two lists of techniques that would otherwise be edited by hand
/// in every technique's pull request: `lib/techniques/all_techniques.dart`,
/// and the status line and the list under "Testing a technique" in
/// `README.md`, between [readmeStatusStart] and [readmeStatusEnd] and between
/// [readmeListStart] and [readmeListEnd].
///
/// Both come from the folders in `lib/techniques/`. A folder `x00_thing`
/// must hold `x00_thing.dart`, which declares `final x00Thing = Technique(`,
/// and the technique must have a doc, `docs/techniques/X00.md`, whose front
/// matter gives its title.
///
///     dart run tool/technique_list.dart          rewrite both files
///     dart run tool/technique_list.dart --check  exit 1 if either is out of date
///
/// `test/docs/technique_list_test.dart` runs the same check in
/// `flutter test`. Two pull requests that each add a technique can conflict
/// in these files; the fix is to take either side and run this tool again.
library;

import 'dart:io';

const allTechniquesPath = 'lib/techniques/all_techniques.dart';
const readmePath = 'README.md';

const readmeStatusStart =
    '<!-- technique-status:start (generated by tool/technique_list.dart; do not edit) -->';
const readmeStatusEnd = '<!-- technique-status:end -->';
const readmeListStart =
    '<!-- technique-list:start (generated by tool/technique_list.dart; do not edit) -->';
const readmeListEnd = '<!-- technique-list:end -->';

final _folderName = RegExp(r'^([a-z])(\d\d)_[a-z0-9]+(?:_[a-z0-9]+)*$');

/// One technique folder in `lib/techniques/`.
class TechniqueFolder {
  TechniqueFolder(this.folder, this.title);

  /// For example `f08_radio_group`.
  final String folder;

  /// From the technique doc's front matter, for example `Radio group`.
  final String title;

  /// For example `F08`.
  String get id => folder.substring(0, 3).toUpperCase();

  /// The name of the [Technique] the folder's file declares, for example
  /// `f08RadioGroup`.
  String get variable {
    final words = folder.split('_');
    return words.first +
        words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
  }
}

/// Every technique folder under [root], in folder name order.
///
/// Throws a [FormatException] for a folder with a name that is not
/// `x00_thing`, two folders with the same id, a folder with no
/// `x00_thing.dart` declaring the technique, or a technique with no doc or
/// no title in it.
List<TechniqueFolder> techniqueFolders(Directory root) {
  final dir = Directory('${root.path}/lib/techniques');
  final names =
      dir
          .listSync()
          .whereType<Directory>()
          .map((d) => d.uri.pathSegments.where((s) => s.isNotEmpty).last)
          .toList()
        ..sort();
  final found = <TechniqueFolder>[];
  final ids = <String, String>{};
  for (final name in names) {
    if (!_folderName.hasMatch(name)) {
      throw FormatException(
        'lib/techniques/$name: a technique folder is named like f08_radio_group',
      );
    }
    final id = name.substring(0, 3).toUpperCase();
    final other = ids[id];
    if (other != null) {
      throw FormatException(
        'lib/techniques/$name: id $id is already used by lib/techniques/$other',
      );
    }
    ids[id] = name;
    final technique = TechniqueFolder(name, _title(root, id));
    final file = File('${dir.path}/$name/$name.dart');
    final declares = RegExp(
      '^final ${technique.variable} = Technique\\(',
      multiLine: true,
    );
    if (!file.existsSync() || !declares.hasMatch(file.readAsStringSync())) {
      throw FormatException(
        'lib/techniques/$name/$name.dart must declare '
        '`final ${technique.variable} = Technique(`',
      );
    }
    found.add(technique);
  }
  if (found.isEmpty) throw const FormatException('no technique folders found');
  return found;
}

String _title(Directory root, String id) {
  final doc = File('${root.path}/docs/techniques/$id.md');
  if (!doc.existsSync()) {
    throw FormatException('docs/techniques/$id.md does not exist');
  }
  final source = doc.readAsStringSync();
  final end = source.indexOf('\n---', 3);
  final title = source.startsWith('---\n') && end > 0
      ? RegExp(
          r'^title:\s*(.+?)\s*$',
          multiLine: true,
        ).firstMatch(source.substring(4, end))?.group(1)
      : null;
  if (title == null) {
    throw FormatException(
      'docs/techniques/$id.md has no title in its front matter',
    );
  }
  return title;
}

/// The group prefixes in catalog order, as `TechniqueGroup` in
/// `lib/catalog/technique.dart` declares them: the order the app and the
/// Widgetbook show the groups in.
List<String> groupOrder(Directory root) {
  final source = File('${root.path}/lib/catalog/technique.dart')
      .readAsStringSync();
  final body = RegExp(
    r'enum TechniqueGroup \{(.*?);',
    dotAll: true,
  ).firstMatch(source);
  final prefixes = [
    for (final m in RegExp(
      r"^\s*\w+\('([A-Z])',",
      multiLine: true,
    ).allMatches(body?.group(1) ?? ''))
      m.group(1)!,
  ];
  if (prefixes.isEmpty) {
    throw const FormatException(
      'lib/catalog/technique.dart: no TechniqueGroup values found',
    );
  }
  return prefixes;
}

/// [techniques] in catalog order: by group, then by id.
List<TechniqueFolder> inCatalogOrder(
  List<TechniqueFolder> techniques,
  List<String> groups,
) {
  final group = <String, int>{};
  for (final t in techniques) {
    final index = groups.indexOf(t.id[0]);
    if (index < 0) {
      throw FormatException('${t.id}: no catalog group has prefix ${t.id[0]}');
    }
    group[t.id] = index;
  }
  return [...techniques]..sort((a, b) {
    final byGroup = group[a.id]!.compareTo(group[b.id]!);
    return byGroup != 0 ? byGroup : a.id.compareTo(b.id);
  });
}

/// `lib/techniques/all_techniques.dart` for [techniques].
String allTechniquesSource(List<TechniqueFolder> techniques) {
  final b = StringBuffer()
    ..writeln('// Generated by tool/technique_list.dart from the folders in')
    ..writeln(
      '// lib/techniques/. Do not edit: run dart run tool/technique_list.dart.',
    )
    ..writeln("import '../catalog/technique.dart';");
  for (final t in techniques) {
    b.writeln("import '${t.folder}/${t.folder}.dart';");
  }
  b
    ..writeln()
    ..writeln(
      '/// Every technique in the catalog, one per folder in lib/techniques/.',
    )
    ..writeln('/// The app and the Widgetbook show them in catalog order.')
    ..writeln('final List<Technique> allTechniques = [');
  for (final t in techniques) {
    b.writeln('  ${t.variable},');
  }
  b.writeln('];');
  return b.toString();
}

/// Ids as the README writes them: "C01, S01 to S05, F07, F08, and I12".
/// Three or more ids in a row in one group are written as a range.
String idList(List<String> ids) {
  final parts = <String>[];
  var i = 0;
  while (i < ids.length) {
    var j = i;
    while (j + 1 < ids.length &&
        ids[j + 1][0] == ids[i][0] &&
        int.parse(ids[j + 1].substring(1)) ==
            int.parse(ids[j].substring(1)) + 1) {
      j++;
    }
    if (j - i >= 2) {
      parts.add('${ids[i]} to ${ids[j]}');
      i = j + 1;
    } else {
      parts.add(ids[i]);
      i++;
    }
  }
  if (parts.length == 1) return parts.single;
  if (parts.length == 2) return '${parts[0]} and ${parts[1]}';
  return '${parts.sublist(0, parts.length - 1).join(', ')}, and ${parts.last}';
}

/// The README's status paragraph. [total] is the number of entries in the
/// coverage inventory, kept from the README as it is.
String readmeStatus(List<TechniqueFolder> techniques, int total) =>
    '''
**Status:** in progress. ${techniques.length} of the $total entries in the
[coverage inventory](docs/coverage-inventory.md) are built, with tests and screen reader transcripts
on Android, iOS, and web: ${idList([for (final t in techniques) t.id])}. They are
listed under [Testing a technique](#testing-a-technique). The rest are planned in
batches in the [plan](docs/plan.md).''';

/// The README's paragraph that links to every technique's tests.
String readmeList(List<TechniqueFolder> techniques) {
  final links = [
    for (final t in techniques)
      '[${t.id} ${t.title}](docs/techniques/${t.id}.md#how-it-is-tested)',
  ];
  final b = StringBuffer(
    '''
Each technique is checked at several layers: widget tests, Playwright on web,
UI Automator on Android, XCUITest on iOS, and screen reader transcripts from
TalkBack and VoiceOver. The commands are in each technique's doc, for example''',
  );
  for (var i = 0; i < links.length; i++) {
    final last = i == links.length - 1;
    final and = links.length > 1 && i == links.length - 2 ? ', and' : ',';
    b.write('\n${links[i]}${last ? '.' : and}');
  }
  return b.toString();
}

/// [source] with the text between [start] and [end] replaced by [body].
String replaceBetween(String source, String start, String end, String body) {
  final from = source.indexOf(start);
  final to = source.indexOf(end);
  if (from < 0 || to < 0 || to < from) {
    throw FormatException('missing or misplaced markers: $start ... $end');
  }
  if (source.indexOf(start, from + 1) >= 0 ||
      source.indexOf(end, to + 1) >= 0) {
    throw FormatException('markers appear more than once: $start');
  }
  return '${source.substring(0, from + start.length)}\n$body\n'
      '${source.substring(to)}';
}

/// [readme] with both generated blocks rewritten for [techniques].
String readmeSource(
  String readme,
  List<TechniqueFolder> techniques,
  List<String> groups,
) {
  final ordered = inCatalogOrder(techniques, groups);
  final from = readme.indexOf(readmeStatusStart);
  final total = from < 0
      ? null
      : RegExp(r'of the (\d+) entries')
            .firstMatch(readme.substring(from))
            ?.group(1);
  if (total == null) {
    throw const FormatException(
      'README.md: the status block must say "of the N entries"',
    );
  }
  final withStatus = replaceBetween(
    readme,
    readmeStatusStart,
    readmeStatusEnd,
    readmeStatus(ordered, int.parse(total)),
  );
  return replaceBetween(
    withStatus,
    readmeListStart,
    readmeListEnd,
    readmeList(ordered),
  );
}

/// What each generated file should hold, by path relative to [root].
Map<String, String> expectedFiles(Directory root) {
  final techniques = techniqueFolders(root);
  final readme = File('${root.path}/$readmePath').readAsStringSync();
  return {
    allTechniquesPath: allTechniquesSource(techniques),
    readmePath: readmeSource(readme, techniques, groupOrder(root)),
  };
}

void main(List<String> args) {
  final unknown = args.where((a) => a != '--check');
  if (unknown.isNotEmpty) {
    stderr.writeln('Usage: dart run tool/technique_list.dart [--check]');
    exit(64);
  }
  final check = args.contains('--check');
  final root = Directory.current;
  final Map<String, String> want;
  try {
    want = expectedFiles(root);
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exit(1);
  }
  var stale = 0;
  for (final MapEntry(key: path, value: content) in want.entries) {
    final file = File('${root.path}/$path');
    if (file.readAsStringSync() == content) continue;
    stale++;
    if (check) {
      stdout.writeln('$path: the list of techniques is out of date');
    } else {
      file.writeAsStringSync(content);
      stdout.writeln('$path: updated');
    }
  }
  if (check && stale > 0) {
    stderr.writeln('Run: dart run tool/technique_list.dart');
    exit(1);
  }
  if (stale == 0) stdout.writeln('The lists of techniques are up to date.');
}
