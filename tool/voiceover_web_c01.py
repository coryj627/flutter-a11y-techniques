#!/usr/bin/env python3
"""L4 for C01 Button on web: capture and check what VoiceOver on macOS speaks.

Runs web_tests/vo/c01_button_vo.spec.js in headed Chromium and Playwright's
WebKit build against build/web (run `flutter build web` first). The spec
drives VoiceOver through Guidepup and asserts the phrases; this script writes
the transcript to docs/evidence/C01/voiceover-web.md.

The run takes over the screen and speaks aloud. It needs Guidepup's setup and
macOS automation permissions (docs/plan.md, finding K5).

Usage: python3 tool/voiceover_web_c01.py
"""
import datetime
import json
import os
import re
import subprocess
import sys

from evidence_common import flutter_version

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB_TESTS = os.path.join(ROOT, "web_tests")


def version(package):
    with open(os.path.join(WEB_TESTS, "node_modules", package, "package.json")) as f:
        return json.load(f)["version"]


def main():
    run = subprocess.run(["npx", "playwright", "test", "c01_button_vo.spec.js"],
                         cwd=os.path.join(WEB_TESTS, "vo"), capture_output=True, text=True)
    log = run.stdout + run.stderr
    # A retried walk prints more than once; the last attempt is the result.
    rows = {}
    for browser, slug, spoken in re.findall(r"^C01VO (\S+) (\S+) \| (.*)$", log, re.M):
        rows[(browser, slug)] = spoken
    if not rows:
        print(log[-3000:])
        sys.exit("No VoiceOver transcript captured.")
    retried = sorted(set(re.findall(r"^\s+✘\s+\d+ \[(\w+)\] › .*? › voiceover reads (\S+)", log, re.M)))
    summary = re.findall(r"^\s+\d+ (?:passed|failed|flaky).*$", log, re.M)
    passed = run.returncode == 0
    macos = subprocess.run(["sw_vers", "-productVersion"], capture_output=True, text=True).stdout.strip()
    out = ["# C01 Button: VoiceOver transcript (web, macOS)", "",
           "Generated by `tool/voiceover_web_c01.py`. Do not edit by hand.", "",
           f"- Date: {datetime.date.today().isoformat()}",
           f"- macOS: {macos}",
           f"- Browsers: Playwright {version('@playwright/test')} Chromium and WebKit builds "
           "(WebKit is not Safari itself)",
           f"- Guidepup: {version('@guidepup/guidepup')}",
           f"- Flutter: {flutter_version()}",
           "- Method: focus the Back button, then `voiceOver.next()` to the activation count",
           "", f"Result: {'PASS' if passed else 'FAIL'} ({'; '.join(s.strip() for s in summary)})"]
    if retried:
        out += ["", "Walks that needed a retry: "
                + ", ".join(f"{slug} ({browser})" for browser, slug in retried) + "."]
    for browser in sorted({b for b, _ in rows}):
        out += ["", f"## {browser}", "", "| Example | Spoken, in order |", "| --- | --- |"]
        out += [f"| `{slug}` | {spoken} |" for (b, slug), spoken in rows.items() if b == browser]
    with open(os.path.join(ROOT, "docs", "evidence", "C01", "voiceover-web.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
