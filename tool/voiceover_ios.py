#!/usr/bin/env python3
"""L4 on iOS: capture and check what VoiceOver speaks for one technique.

Runs the technique's testVoiceOverSpeech UI test on an iOS 27 simulator. The test
drives VoiceOver through XCUIVoiceOverService and asserts the phrases; this
script writes the transcript to docs/evidence/<ID>/voiceover-ios.md.

Usage: python3 tool/voiceover_ios.py <ID> ["iPhone 17"]
"""
import datetime
import os
import re
import subprocess
import sys

from evidence_common import TECHNIQUES, flutter_version, technique_argument

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEVICE = sys.argv[2] if len(sys.argv) > 2 else "iPhone 17"

WALK = ("`XCUIVoiceOverService.moveForward()` from the top of each example screen to its "
        "last element", "Spoken, in swipe order")
# technique -> (how the speech was captured, heading of the transcript column)
METHODS = {
    "I12": ("the VoiceOver cursor is put on the example's button, the button is activated "
            "with a double tap, and `XCUIVoiceOverService.currentSpeech()` is read until the "
            "message is heard, or for four seconds after the visible change when nothing "
            "should be said. The message must be on screen first. The cursor is then moved "
            "back and forward once, which must land on the button again, to show that the "
            "message was announced and not reached by a moved cursor",
            "Spoken: on the button / after it is activated / after one step back and forward"),
}


def main():
    technique = technique_argument(sys.argv, 'Usage: python3 tool/voiceover_ios.py <ID> ["iPhone 17"]')
    title, _, ios_test, _ = TECHNIQUES[technique]
    if ios_test is None:
        sys.exit(f"{technique} has no VoiceOver test on iOS; see its technique doc for why.")
    run = subprocess.run(
        ["xcodebuild", "test", "-workspace", "Runner.xcworkspace", "-scheme", "Runner",
         "-configuration", "Debug", "-destination", f"platform=iOS Simulator,name={DEVICE}",
         f"-only-testing:RunnerUITests/{ios_test}/testVoiceOverSpeech",
         "-derivedDataPath", os.path.join(ROOT, "build", "ios_uitest")],
        cwd=os.path.join(ROOT, "ios"), capture_output=True, text=True)
    log = run.stdout + run.stderr
    rows = re.findall(rf"^{technique}VO (\S+) \| (.*)$", log, re.M)
    failures = re.findall(r"error: .*? : (.*)$", log, re.M)
    if not rows:
        print(log[-3000:])
        sys.exit("No VoiceOver transcript captured.")
    os_version = re.search(r"OS:(\d+(?:\.\d+)*)", log) or re.search(r"iOS (\d+(?:\.\d+)*)", log)
    xcode = subprocess.run(["xcodebuild", "-version"], capture_output=True, text=True).stdout.split("\n")[0]
    passed = run.returncode == 0
    method, column = METHODS.get(technique, WALK)
    out = [f"# {title}: VoiceOver transcript (iOS)", "",
           f"Generated by `python3 tool/voiceover_ios.py {technique}`. Do not edit by hand.", "",
           f"- Date: {datetime.date.today().isoformat()}",
           f"- Device: {DEVICE} (simulator)",
           f"- iOS: {os_version.group(1) if os_version else 'unknown'}",
           f"- {xcode}",
           f"- Flutter: {flutter_version()}",
           f"- Method: {method}; utterances are cut at 64 characters by the API",
           "", f"Result: {'PASS' if passed else 'FAIL'}", "",
           f"| Example | {column} |", "| --- | --- |"]
    out += [f"| `{slug}` | {spoken} |" for slug, spoken in rows]
    if failures:
        out += ["", "## Failures", ""] + [f"- {f}" for f in failures]
    os.makedirs(os.path.join(ROOT, "docs", "evidence", technique), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "evidence", technique, "voiceover-ios.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
