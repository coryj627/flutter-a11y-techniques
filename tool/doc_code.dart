/// Keeps the "Example code" section of each technique doc equal to the code
/// in the technique's `examples.dart` (decision D24 in docs/requirements.md).
///
/// Each example in `examples.dart` sits between `// #region <slug>` and
/// `// #endregion`. Each doc in `docs/techniques/` has a generated block
/// between [startMarker] and [endMarker]; this tool rewrites that block from
/// the regions, so the code in the docs is the code that is tested.
///
///     dart run tool/doc_code.dart          rewrite the docs
///     dart run tool/doc_code.dart --check  exit 1 if any doc is out of date
///
/// `test/docs/doc_code_test.dart` runs the same check in `flutter test`.
library;

import 'dart:io';

const startMarker =
    '<!-- example-code:start (generated by tool/doc_code.dart; do not edit) -->';
const endMarker = '<!-- example-code:end -->';

final _regionStart = RegExp(r'^// #region (\S+)\s*$');
final _regionEnd = RegExp(r'^// #endregion\s*$');
final _codeLink = RegExp(
  r'\]\(\.\./\.\./(lib/techniques/[\w/]+/examples\.dart)\)',
);

/// The code of each region in [source], by slug, in file order.
///
/// Throws a [FormatException] for a region that is nested, unclosed, empty,
/// or repeated, or that contains a Markdown code fence.
Map<String, String> regions(String source) {
  final found = <String, String>{};
  String? open;
  var lines = <String>[];
  var number = 0;
  for (final line in source.split('\n')) {
    number++;
    final start = _regionStart.firstMatch(line);
    if (start != null) {
      if (open != null) {
        throw FormatException('line $number: region inside region "$open"');
      }
      open = start.group(1)!;
      if (found.containsKey(open)) {
        throw FormatException('line $number: region "$open" appears twice');
      }
      lines = [];
    } else if (_regionEnd.hasMatch(line)) {
      if (open == null) {
        throw FormatException('line $number: #endregion without #region');
      }
      final code = lines.join('\n').trim();
      if (code.isEmpty) {
        throw FormatException('line $number: region "$open" is empty');
      }
      found[open] = code;
      open = null;
    } else if (open != null) {
      if (line.contains('```')) {
        throw FormatException(
          'line $number: region "$open" contains a code fence',
        );
      }
      lines.add(line);
    }
  }
  if (open != null) throw FormatException('region "$open" is not closed');
  return found;
}

/// The generated block for [examples], markers included.
String block(Map<String, String> examples, String examplesPath) {
  final out = StringBuffer()
    ..writeln(startMarker)
    ..writeln('## Example code')
    ..writeln()
    ..writeln('Copied from `$examplesPath` by')
    ..writeln(
      '`dart run tool/doc_code.dart`. Each example is the whole widget the '
      'tests',
    )
    ..writeln(
      'run, including the `TestId` wrappers they use to find its elements.',
    );
  for (final MapEntry(key: slug, value: code) in examples.entries) {
    out
      ..writeln()
      ..writeln('### `$slug`')
      ..writeln()
      ..writeln('```dart')
      ..writeln(code)
      ..writeln('```');
  }
  out.write(endMarker);
  return out.toString();
}

/// The path of the examples file a technique doc links to, relative to the
/// repository root.
String examplesPathOf(String doc) {
  final match = _codeLink.firstMatch(doc);
  if (match == null) {
    throw const FormatException('no link to lib/techniques/…/examples.dart');
  }
  return match.group(1)!;
}

/// [doc] with its generated block rebuilt from [examplesSource].
String sync(String doc, String examplesSource, String examplesPath) {
  final start = doc.indexOf(startMarker);
  final end = doc.indexOf(endMarker);
  if (start < 0 || end < start) {
    throw const FormatException('no example-code markers');
  }
  if (doc.indexOf(startMarker, start + 1) >= 0 ||
      doc.indexOf(endMarker, end + 1) >= 0) {
    throw const FormatException('more than one example-code block');
  }
  return doc.substring(0, start) +
      block(regions(examplesSource), examplesPath) +
      doc.substring(end + endMarker.length);
}

/// The technique docs under [root]: `docs/techniques/*.md`.
List<File> techniqueDocs(Directory root) {
  final files = Directory('${root.path}/docs/techniques')
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.md'))
      .toList();
  files.sort((a, b) => a.path.compareTo(b.path));
  return files;
}

/// [doc]'s content as it should be, read from the files under [root].
String expected(File doc, Directory root) {
  final source = doc.readAsStringSync();
  final path = examplesPathOf(source);
  final examples = File('${root.path}/$path');
  if (!examples.existsSync()) throw FormatException('$path does not exist');
  return sync(source, examples.readAsStringSync(), path);
}

void main(List<String> args) {
  final unknown = args.where((a) => a != '--check');
  if (unknown.isNotEmpty) {
    stderr.writeln('Usage: dart run tool/doc_code.dart [--check]');
    exit(64);
  }
  final check = args.contains('--check');
  final root = Directory.current;
  var stale = 0;
  var failed = 0;
  for (final doc in techniqueDocs(root)) {
    final name = doc.path.substring(root.path.length + 1);
    try {
      final want = expected(doc, root);
      if (want == doc.readAsStringSync()) continue;
      stale++;
      if (check) {
        stdout.writeln('$name: example code is out of date');
      } else {
        doc.writeAsStringSync(want);
        stdout.writeln('$name: updated');
      }
    } on FormatException catch (e) {
      failed++;
      stderr.writeln('$name: ${e.message}');
    }
  }
  if (failed > 0) exit(1);
  if (check && stale > 0) {
    stderr.writeln('Run: dart run tool/doc_code.dart');
    exit(1);
  }
  if (stale == 0) stdout.writeln('Example code in the docs is up to date.');
}
